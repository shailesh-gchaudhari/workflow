# List of numbers
numbers = [1, 45, 23, 89, 97, 12, 9, 34, 56, 108]

# Find highest number
highest = max(numbers)

# Find lowest number
lowest = min(numbers)

# Find average
average = sum(numbers) / len(numbers)

# Display results
print("Highest number:", highest)
print("Lowest number:", lowest)
print("Average:", average)
