# List of numbers
numbers = [10, 45, 23, 89, 67, 12, 99, 34, 56, 78]

# Find highest number
highest = max(numbers)

# Find lowest number
lowest = min(numbers)

# Find average
average = sum(numbers) / len(numbers)

# Display results
print("Highest number:", highest)
print("Lowest number:", lowest)
print("Average:", average)
